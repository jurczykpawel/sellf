import { resetAffiliateDatabase } from '../database';
import { execFileSync } from 'node:child_process';
import { createClient } from '@supabase/supabase-js';
import { beforeAll, expect, it, vi } from 'vitest';
const context = vi.hoisted(() => ({ client: undefined as unknown }));
vi.mock('@/lib/actions/admin-auth', () => ({ withAdminClient: async (fn: (ctx: unknown) => unknown) => fn({ user: { id: 'dddddddd-0000-4000-a000-000000000000' }, dataClient: context.client }) }));
vi.mock('next/cache', () => ({ revalidatePath: vi.fn() }));
import { reservePayout, markPayoutPaid, cancelPayout, adjustCommission } from '@/lib/affiliates/payouts/actions';
import { getPayoutChoices, previewPayout } from '@/lib/affiliates/payouts/reads';
import { downloadPayoutCsv } from '@/lib/affiliates/payouts/download';
function sql(query: string): string { return execFileSync('docker', ['exec', 'supabase_db_sellf-afffix', 'psql', '-U', 'postgres', '-qAt', '-v', 'ON_ERROR_STOP=1', '-c', query], { encoding: 'utf8' }).trim(); }
const env = JSON.parse(execFileSync('supabase', ['status', '--workdir', '/private/tmp/sellf-afffix', '-o', 'json'], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }));
const db = createClient(env.API_URL, env.SERVICE_ROLE_KEY, { auth: { persistSession: false } });
context.client = db;
beforeAll(() => {
  resetAffiliateDatabase();
  expect(env.API_URL).toBe('http://127.0.0.1:55531');
}, 125000);
const member = 'af000000-0000-4000-a000-000000000001';
const payment = 'af000000-0000-4000-a000-000000000010';
function sync(): void { sql("SELECT public.affiliate_apply_sync(payment_id,lease_token,requested_generation,'2026-01-02',false) FROM public.affiliate_claim_work(100)"); }
const cutoff = () => new Date(sql('SELECT clock_timestamp()')).toISOString();
const preview = () => previewPayout({ member_id: member, currency: 'PLN', cutoff: cutoff() });
it('runs the seeded manual payout lifecycle and retains debt after actual settlement', async () => {
  const options = await getPayoutChoices({ search: 'Demo' });
  expect(options.data?.members[0].display_name).toBe('Demo Partner');
  const before = await preview();
  expect(before.data).toMatchObject({ payable_minor: '2000', available: true, held_minor: '2000' });
  const input = { member_id: member, currency: 'PLN', cutoff: cutoff(), member_version: '1', program_version: '1', payee_reference: 'demo-payee' };
  const attempts = await Promise.all([reservePayout(input), reservePayout(input)]);
  expect(attempts.filter(r => r.success)).toHaveLength(1);
  const payout = attempts.find(r => r.success)!.data!;
  const response = await downloadPayoutCsv({ payout_id: payout.id, version: payout.version });
  expect(response.status).toBe(200);
  expect(response.headers.get('Cache-Control')).toContain('no-store');
  const csv = await response.text();
  expect(csv).toContain('2000,0,2000,demo-payee');
  expect(csv).not.toContain('affiliate-customer');
  expect(sql("SELECT count(*) FROM public.affiliate_ledger WHERE kind='settlement'")).toBe('0');
  sql(`UPDATE public.payment_transactions SET refunded_amount=6150 WHERE id='${payment}'`);
  expect((await preview()).data?.sync_required).toBe(true);
  expect((await downloadPayoutCsv({ payout_id: payout.id, version: '1' })).status).toBe(409);
  expect(sql(`SELECT count(*) FROM public.affiliate_payout_allocations WHERE payout_id='${payout.id}' AND released_at IS NULL`)).toBe('1');
  expect((await reservePayout(input)).errorCode).toBe('409');
  sync();
  const version = sql(`SELECT version FROM public.affiliate_payouts WHERE id='${payout.id}'`);
  expect((await downloadPayoutCsv({ payout_id: payout.id, version })).status).toBe(409);
  const paid = { payout_id: payout.id, version, bank_reference: 'bank-a16', invoice_reference: 'invoice-a16', bank_amount_minor: '2460', currency: 'PLN', paid_at: '2026-10-01T12:00:00Z', full_settlement: true };
  expect((await markPayoutPaid(paid)).success).toBe(false);
  const evidence = { ...paid, reason: 'Full old reservation settled', evidence_reference: 'bank-record-a16' };
  expect((await markPayoutPaid(evidence)).success).toBe(true);
  expect((await markPayoutPaid(evidence)).success).toBe(true);
  expect((await markPayoutPaid({ ...evidence, bank_amount_minor: '2461' })).errorCode).toBe('409');
  expect(sql(`SELECT sum(amount_minor) FROM public.affiliate_ledger WHERE currency='PLN' AND (payout_id='${payout.id}' OR commission_id=(SELECT id FROM public.affiliate_commissions WHERE payment_id='${payment}'))`)).toBe('-1000');
  expect((await preview()).data).toMatchObject({ debt_offset_minor: '1000', payable_minor: '-1000', available: false });
  sql(`UPDATE public.payment_transactions SET refunded_amount=12300 WHERE id='${payment}'`); sync();
  expect((await preview()).data).toMatchObject({ debt_offset_minor: '2000', payable_minor: '-2000', available: false });
  { // Continue the same seeded settlement scenario in a second currency.
  const input = { member_id: member, currency: 'EUR', cutoff: cutoff(), member_version: '1', program_version: '1', payee_reference: 'demo-eur' };
  expect((await reservePayout({ ...input, currency: 'USD' })).success).toBe(false);
  expect((await reservePayout({ ...input, member_version: '2' })).errorCode).toBe('409');
  expect((await db.rpc('affiliate_member_update', { p_actor: 'dddddddd-0000-4000-a000-000000000000', p_member: member, p_expected_version: '1', p_status: 'suspended', p_reason: 'Membership paused' })).error).toBeNull();
  expect((await reservePayout({ ...input, member_version: '2' })).success).toBe(false);
  expect((await db.rpc('affiliate_member_update', { p_actor: 'dddddddd-0000-4000-a000-000000000000', p_member: member, p_expected_version: '2', p_status: 'approved', p_reason: 'Membership resumed' })).error).toBeNull();
  input.member_version = '3';
  const options = await getPayoutChoices({ search: 'Demo', member_id: member, commission_search: 'EUR' });
  expect(options.data?.commissions[0].product_name).toBe('Affiliate EUR Toolkit');
  const payout = (await reservePayout(input)).data!;
  expect((await markPayoutPaid({ payout_id: payout.id, version: '1', bank_reference: 'bank-a16', invoice_reference: 'invoice-eur', bank_amount_minor: '2000', currency: 'EUR', paid_at: '2026-10-01T12:00:00Z', full_settlement: true })).errorCode).toBe('409');
  expect((await cancelPayout({ payout_id: payout.id, version: '1', no_transfer: true, reason: 'Bank checked' })).success).toBe(true);
  const pid = 'af000000-0000-4000-a000-000000000011';
  sql(`UPDATE public.payment_transactions SET status='disputed' WHERE id='${pid}'`); sync();
  expect((await reservePayout(input)).success).toBe(false);
  const c = JSON.parse(sql(`SELECT json_build_object('id',id,'version',version::text) FROM public.affiliate_commissions WHERE payment_id='${pid}'`));
  expect((await adjustCommission({ commission_id: c.id, version: c.version, amount_minor: '2000', reason: 'Dispute reviewed', evidence_reference: 'case-a16', review_dispute: true })).success).toBe(true);
  input.cutoff = cutoff();
  const restored = (await reservePayout(input)).data!;
  expect(restored).toBeDefined();
  const exactPaid = { payout_id: restored.id, version: restored.version, bank_reference: 'bank-eur-a16', invoice_reference: 'invoice-eur', bank_amount_minor: '9007199254740993', currency: 'EUR', paid_at: '2026-10-01T12:00:00Z', full_settlement: true };
  expect((await markPayoutPaid(exactPaid)).success).toBe(true);
  expect(sql(`SELECT bank_amount_minor::text FROM public.affiliate_payouts WHERE id='${restored.id}'`)).toBe('9007199254740993');
  expect(sql(`SELECT metadata FROM public.payment_transactions WHERE id='${pid}'`)).toBe('{}');
  }
});
