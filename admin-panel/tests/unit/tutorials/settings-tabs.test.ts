// @vitest-environment happy-dom
import React from 'react';
import { cleanup, fireEvent, render, screen } from '@testing-library/react';
import { afterEach, expect, it, vi } from 'vitest';
import SettingsTabs from '@/components/settings/SettingsTabs';
const state = vi.hoisted(() => ({ params: new URLSearchParams('tab=payments') }));
vi.mock('next/navigation', () => ({ useSearchParams: () => state.params }));
vi.mock('next-intl', () => ({ useTranslations: () => (key: string) => key }));
vi.mock('@/components/providers/config-provider', () => ({ useConfig: () => ({ demoMode: false }) }));
vi.mock('@/contexts/AuthContext', () => ({ useAuth: () => ({ role: 'platform_admin' }) }));
vi.mock('@/components/settings/BankTransferSettings', () => ({ default: () => React.createElement('div', null, 'BankTransferSettings') }));
vi.mock('@/components/settings/InvoicingSettings', () => ({ default: () => React.createElement('div', null, 'InvoicingSettings') }));
vi.mock('@/components/settings/ShopSettings', () => ({ default: () => React.createElement('div', null, 'ShopSettings') }));
vi.mock('@/components/settings/BuyerEmailSettings', () => ({ default: () => React.createElement('div', null, 'BuyerEmailSettings') }));
vi.mock('@/components/settings/BrandingSettings', () => ({ default: () => React.createElement('div', null, 'BrandingSettings') }));
vi.mock('@/components/settings/CheckoutThemeSettings', () => ({ default: () => React.createElement('div', null, 'CheckoutThemeSettings') }));
vi.mock('@/components/settings/StripeSettings', () => ({ default: () => React.createElement('div', null, 'StripeSettings') }));
vi.mock('@/components/settings/StripeTaxSettings', () => ({ default: () => React.createElement('div', null, 'StripeTaxSettings') }));
vi.mock('@/components/settings/PaymentMethodSettingsWrapper', () => ({ default: () => React.createElement('div', null, 'PaymentMethodSettingsWrapper') }));
vi.mock('@/components/settings/LegalDocumentsSettings', () => ({ default: () => React.createElement('div', null, 'LegalDocumentsSettings') }));
vi.mock('@/components/settings/OmnibusSettings', () => ({ default: () => React.createElement('div', null, 'OmnibusSettings') }));
vi.mock('@/components/settings/AttributionSettings', () => ({ default: () => React.createElement('div', null, 'AttributionSettings') }));
vi.mock('@/components/settings/LicenseSettings', () => ({ default: () => React.createElement('div', null, 'LicenseSettings') }));
vi.mock('@/components/settings/LicenseKeysSettings', () => ({ default: () => React.createElement('div', null, 'LicenseKeysSettings') }));
vi.mock('@/components/settings/SystemUpdateSettings', () => ({ default: () => React.createElement('div', null, 'SystemUpdateSettings') }));
vi.mock('@/components/settings/SecurityAuditSettings', () => ({ default: () => React.createElement('div', null, 'SecurityAuditSettings') }));
afterEach(cleanup);
it('follows tutorial navigation between settings tabs without remounting and preserves manual selection', () => {
  const view = render(React.createElement(SettingsTabs, { siteUrl: 'https://example.com' }));
  expect(screen.queryByText('BankTransferSettings')).not.toBeNull();
  state.params = new URLSearchParams('tab=legal&tutorial=attribution');
  view.rerender(React.createElement(SettingsTabs, { siteUrl: 'https://example.com' }));
  expect(screen.queryByText('AttributionSettings')).not.toBeNull();
  expect(screen.queryByText('BankTransferSettings')).toBeNull();
  state.params = new URLSearchParams('tab=payments&tutorial=bank-transfer-setup');
  view.rerender(React.createElement(SettingsTabs, { siteUrl: 'https://example.com' }));
  expect(screen.queryByText('BankTransferSettings')).not.toBeNull();
  state.params = new URLSearchParams('tab=payments');
  view.rerender(React.createElement(SettingsTabs, { siteUrl: 'https://example.com' }));
  fireEvent.click(screen.getByText('tabs.shop'));
  expect(screen.queryByText('ShopSettings')).not.toBeNull();
  state.params = new URLSearchParams('tab=payments&tutorial=bank-transfer-setup');
  view.rerender(React.createElement(SettingsTabs, { siteUrl: 'https://example.com' }));
  expect(screen.queryByText('BankTransferSettings')).not.toBeNull();
  fireEvent.click(screen.getByText('tabs.shop'));
  state.params = new URLSearchParams('tab=payments');
  view.rerender(React.createElement(SettingsTabs, { siteUrl: 'https://example.com' }));
  expect(screen.queryByText('ShopSettings')).not.toBeNull();
});
